import AppKit
import PPasteCore

final class PasteboardWatcher {
    private let store: ClipStore
    private let imageDir: URL
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Password managers and similar; their copies are never stored.
    static let ignoredBundleIDs: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
        "com.apple.keychainaccess", "com.apple.Passwords", "org.keepassxc.keepassxc",
    ]
    private static let skipTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                    "org.nspasteboard.AutoGeneratedType"].map(NSPasteboard.PasteboardType.init(rawValue:))

    var onChange: (() -> Void)?

    init(store: ClipStore, imageDir: URL) { self.store = store; self.imageDir = imageDir }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }

    /// Call after ppaste writes to the pasteboard itself so it isn't recaptured as a new copy.
    func ignoreCurrentChange() { lastChange = NSPasteboard.general.changeCount }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        let types = Set(pb.types ?? [])
        if Self.skipTypes.contains(where: types.contains) { return }
        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier, Self.ignoredBundleIDs.contains(id) { return }

        var item: ClipItem?
        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item = ClipItem(kind: ClipItem.kind(forText: text), text: text,
                            contentHash: ClipStore.hash(Data(text.utf8)))
        } else if let png = imageData(from: pb) {
            let hash = ClipStore.hash(png)
            let url = imageDir.appendingPathComponent("\(hash).png")
            if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url) }
            item = ClipItem(kind: .image, imagePath: url.path, contentHash: hash)
        }
        guard var item else { return }
        item.sourceBundleID = app?.bundleIdentifier
        item.sourceName = app?.localizedName
        try? store.save(item)
        onChange?()
    }

    private func imageData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }
}
